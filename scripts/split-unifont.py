#!/usr/bin/env python3
"""Split GNU Unifont into small WOFF2 chunks with exact `unicode-range`s.

Browsers only download the chunks that contain characters actually used on the
page, so the whole BMP (~57k glyphs) stays available without a 1.6 MB download.

Usage (needs `pip install fonttools brotli`):
    python3 scripts/split-unifont.py node_modules/@fontsource/unifont/files/unifont-latin-400-normal.woff2
"""
import io
import os
import sys
from itertools import groupby

from fontTools import subset
from fontTools.ttLib import TTFont

FAMILY = "Clawd Unifont"
OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "public", "fonts", "unifont")
MAX_PER_CHUNK = 640


def ranges(cps):
    """[0x41, 0x42, 0x43, 0x50] -> 'U+41-43, U+50'"""
    out = []
    for _, grp in groupby(enumerate(cps), key=lambda t: t[1] - t[0]):
        grp = [c for _, c in grp]
        a, b = grp[0], grp[-1]
        out.append(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}")
    return ", ".join(out)


def main(src):
    # Decode the (possibly WOFF2) source once; re-parsing WOFF2 per chunk is very slow.
    font = TTFont(src)
    font.flavor = None
    buf = io.BytesIO()
    font.save(buf)
    raw = buf.getvalue()
    font = TTFont(io.BytesIO(raw))
    cps = sorted(c for c in font.getBestCmap() if c >= 0x20)

    # Bucket by 256-codepoint page, then merge neighbouring small pages.
    pages = [list(g) for _, g in groupby(cps, key=lambda c: c >> 8)]
    chunks, cur = [], []
    for page in pages:
        if cur and len(cur) + len(page) > MAX_PER_CHUNK:
            chunks.append(cur)
            cur = []
        cur = cur + page
    if cur:
        chunks.append(cur)

    os.makedirs(OUT_DIR, exist_ok=True)
    for f in os.listdir(OUT_DIR):
        if f.endswith(".woff2"):
            os.remove(os.path.join(OUT_DIR, f))

    css = [f"/* GNU Unifont {font['name'].getDebugName(5)} — SIL OFL 1.1. Generated by scripts/split-unifont.py */"]
    for i, chunk in enumerate(chunks):
        name = f"unifont-{i:03d}.woff2"
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = False
        opts.hinting = False
        sub = subset.Subsetter(opts)
        f = TTFont(io.BytesIO(raw), lazy=True)
        sub.populate(unicodes=chunk)
        sub.subset(f)
        f.flavor = "woff2"
        f.save(os.path.join(OUT_DIR, name))
        css.append(
            "@font-face {\n"
            f'  font-family: "{FAMILY}";\n'
            "  font-style: normal;\n"
            "  font-weight: 400;\n"
            "  font-display: block;\n"
            f'  src: url("./{name}") format("woff2");\n'
            f"  unicode-range: {ranges(chunk)};\n"
            "}"
        )
    with open(os.path.join(OUT_DIR, "unifont.css"), "w") as fh:
        fh.write("\n".join(css) + "\n")
    print(f"{len(cps)} codepoints -> {len(chunks)} chunks")


if __name__ == "__main__":
    main(sys.argv[1])
