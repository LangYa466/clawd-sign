export type IconName = keyof typeof MAPS;

const PATHS = Object.fromEntries(
  Object.entries(MAPS).map(([name, rows]) => {
    let d = '';
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] !== '#') {
          x++;
          continue;
        }
        let end = x;
        while (end < row.length && row[end] === '#') end++;
        d += `M${x} ${y}h${end - x}v1h${x - end}z`;
        x = end;
      }
    });
    return [name, d];
  }),
) as Record<IconName, string>;

export function Icon({ name, size = 16, ...rest }: { name: IconName; size?: number } & SVGProps<SVGSVGElement>) {
  return (
    <svg viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true" focusable="false" {...rest}>
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  );
}
